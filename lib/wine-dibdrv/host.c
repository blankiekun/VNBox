/* hostdibdrv.cpp copies the guest's i386 dib_info bytes as they are and swaps in host pointers at these offsets. */
_Static_assert(sizeof(void *) == 4, "host DIB primitives need 32-bit pointers (wasm32)");
_Static_assert(sizeof(dib_info) == 100, "dib_info layout differs from i386 Wine's");
_Static_assert(offsetof(dib_info, rect) == 16 && offsetof(dib_info, stride) == 32 && offsetof(dib_info, bits) == 36,
               "dib_info layout differs from i386 Wine's");
_Static_assert(offsetof(dib_info, color_table) == 88 && offsetof(dib_info, color_table_size) == 92 &&
               offsetof(dib_info, funcs) == 96, "dib_info layout differs from i386 Wine's");
_Static_assert(sizeof(struct intensity_range) == 6 && sizeof(struct font_gamma_ramp) == 516 && sizeof(TRIVERTEX) == 16 &&
               sizeof(struct stretch_params) == 24 && sizeof(rop_mask_bits) == 8 && sizeof(struct line_params) == 32,
               "struct layout differs from i386 Wine's");

/* Same order as the vnbox_dibdrv_funcs export of the patched win32u.so (vn/wine/win32u-dibdrv-export.patch). */
static const primitive_funcs *const tables[9] =
{
    &funcs_8888, &funcs_32, &funcs_24, &funcs_555, &funcs_16, &funcs_8, &funcs_4, &funcs_1, &funcs_null
};

/* Slot `slot` (the field's index in primitive_funcs) of table `table`. */
void (*vnbox_dibdrv_host_fn(unsigned table, unsigned slot))(void)
{
    if (table >= 9 || slot >= sizeof(primitive_funcs) / sizeof(void (*)(void))) return NULL;
    return ((void (*const *)(void))tables[table])[slot];
}

/* Table `table` itself (what a host dib_info's funcs points at). */
const void *vnbox_dibdrv_host_table(unsigned table)
{
    return table < 9 ? tables[table] : NULL;
}

